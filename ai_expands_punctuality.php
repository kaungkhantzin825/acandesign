        <h2 class="blog-post__section-title">時間を守ることより、大切にしたかったこと</h2>

        <p>以前、ミャンマーのスタッフの遅刻に悩んでいた時期がありました。</p>
        <p>始業時間になっても出社していないメンバーがいる。</p>
        <p>そのたびに理由を確認し、注意をし、時間を守るよう指導する。</p>
        <p>会社として決めたルールなのだから、守るのは当然。</p>
        <p>当時の私は、そう考えていました。</p>
        <p>もちろん、今でも時間を守ることは大切だと思っています。</p>
        <p>しかし、スタッフとの対話を重ねる中で、私自身の考え方が少しずつ変わっていきました。</p>

        <h3 class="blog-post__subsection-title">遅刻したくて、遅刻しているわけではない</h3>
        <p>何度も遅刻を繰り返すメンバーがいると、どうしても本人の意識や責任感に原因があるのではないかと考えてしまいます。</p>
        <p>私も最初はそうでした。</p>
        <p>しかし、一人ひとりの話を聞いてみると、違う事情が見えてきました。</p>
        <p>大きな要因の一つが、ミャンマーの交通事情です。</p>
        <p>通勤にかかる時間が読みづらい。</p>
        <p>予定どおりに家を出ても、道路の状況によって到着時間が大きく変わることがある。</p>
        <p>本人の努力だけでは、どうにもならないことがあるのです。</p>
        <p>もちろん、すべての遅刻を交通事情だけで説明できるわけではありません。</p>
        <p>それでも、話を聞かずに本人の意識の問題だと決めつけていたら、本当の原因には気づけなかったと思います。</p>
        <p>私は、少し反省しました。</p>
        <p>日本で当たり前だと思っていることを、そのままミャンマーのスタッフにも求めていたのではないか。</p>
        <p>現地の事情を理解しているつもりで、本当には理解できていなかったのかもしれません。</p>

        <h3 class="blog-post__subsection-title">何のために時間を管理するのか</h3>
        <p>そこで、改めて考えました。</p>
        <p>私たちの仕事にとって、本当に大切なことは何だろう。</p>
        <p>朝、決められた時間に全員が席についていることでしょうか。</p>
        <p>それとも、お客様からお預かりした仕事を、品質を守りながら、約束した期限までに完了させることでしょうか。</p>
        <p>もちろん、業務によっては決まった時間に対応する必要があります。</p>
        <p>お客様との打ち合わせや、リアルタイムでの作業、チーム内での連携など、時間を合わせなければ成り立たない仕事もあります。</p>
        <p>しかし、すべての仕事がそうとは限りません。</p>
        <div class="blog-post__intro">
          <p>決められたタスクを、責任を持って完了させる。</p>
        </div>
        <p>その原則が守られるのであれば、必ずしも全員が同じ時間に出社する必要はないのではないか。</p>
        <p>そう考えるようになりました。</p>

        <h3 class="blog-post__subsection-title">管理を変えてみることにした</h3>
        <p>そこで、勤務体系をフレックスタイム制に変更しました。</p>
        <p>基本となる考え方はシンプルです。</p>
        <div class="blog-post__intro">
          <p>担当するタスクを、約束した期限までに完了させること。</p>
        </div>
        <p>そのうえで、業務に支障がない範囲で勤務時間を調整できるようにしました。</p>
        <p>さらに、状況によっては在宅勤務も選択できるようにしています。</p>
        <p>交通事情が厳しい日に、無理に時間をかけて出社する必要があるのか。</p>
        <p>自宅で同じ仕事ができるのであれば、その方が効率的ではないか。</p>
        <p>もちろん、情報セキュリティや業務品質、チーム内の連絡体制は維持しなければなりません。</p>
        <p>自由に働けることと、責任がないことは違います。</p>
        <p>むしろ、自分で勤務時間や作業の進め方を考えるからこそ、これまで以上に責任感が必要になります。</p>
        <p>私は、その責任をメンバーに委ねてみることにしました。</p>

        <h3 class="blog-post__subsection-title">結果は、想像していた以上だった</h3>
        <p>勤務体系を変更した結果、業務の効率化が進み、稼働率も向上しました。</p>
        <p>これは、私にとって大きな発見でした。</p>
        <p>これまでは、遅刻をなくすために指導することに時間を使っていました。</p>
        <p>しかし、ルールを変えることで、遅刻そのものを問題にする必要が減り、メンバーも仕事に集中しやすくなったのです。</p>
        <p>通勤の負担を減らし、自分の状況に合わせて仕事を進められる。</p>
        <p>その結果、会社にとっても良い成果が得られました。</p>
        <p>もちろん、フレックスにすれば、どの会社でも同じ結果になるとは限りません。</p>
        <p>仕事の内容やメンバーの習熟度、チームの連絡状況によって、適切な管理方法は異なります。</p>
        <p>ただ、今回の経験から学んだことがあります。</p>
        <div class="blog-post__intro">
          <p>社員の行動を変えることが、経営者の仕事ではない。</p>
        </div>
        <p>社員が能力を発揮できるように、会社の仕組みを変えることも、経営者の大切な役割なのだということです。</p>

        <h3 class="blog-post__subsection-title">ミャンマーは、日本と同じではない</h3>
        <p>私は長くミャンマーで仕事をしてきました。</p>
        <p>それでも、日本の感覚で物事を考えてしまうことがあります。</p>
        <p>日本では当たり前にできることが、ミャンマーでは簡単ではない。</p>
        <p>交通事情だけではありません。</p>
        <p>電力や通信など、仕事を取り巻く環境にも違いがあります。</p>
        <p>こうした環境を、日本と同じ基準で評価することには無理があるのかもしれません。</p>
        <p>一方で、私がいつも感じていることがあります。</p>
        <p>それは、仕事をしたい、もっと成長したい、スキルを身につけたいという気持ちは、日本もミャンマーも変わらないということです。</p>
        <p>むしろ、限られた環境の中でも学ぼうとする姿勢に、私自身が刺激を受けることも少なくありません。</p>
        <p>彼らに必要なのは、日本と同じ環境やルールを押しつけることではなく、その環境の中で力を発揮できる仕組みなのだと思います。</p>

        <h3 class="blog-post__subsection-title">自主性を尊重するということ</h3>
        <p>ここ最近、A CAN SOLUTIONSのメンバーの成長を感じる機会が増えました。</p>
        <p>セキュリティのトラブルに、自分たちで考えながら対応するメンバー。</p>
        <p>AIツールを使い、新しい仕事に挑戦するメンバー。</p>
        <p>そして、自分の勤務時間を調整しながら、担当する仕事を責任を持って進めるメンバー。</p>
        <p>こうした姿を見るたびに、私自身の経営に対する考え方も変わってきています。</p>
        <p>以前は、管理することが経営者の重要な仕事だと思っていました。</p>
        <p>もちろん、今でも管理は必要です。</p>
        <p>特に、お客様の情報を扱う仕事では、セキュリティや品質に関するルールを守ることは欠かせません。</p>
        <p>しかし、すべてを細かく管理することが、必ずしも良い結果につながるとは限りません。</p>
        <div class="blog-post__intro">
          <p>守るべきルールは明確にする。<br />そのうえで、仕事の進め方についてはメンバーの自主性を尊重する。<br />そして、結果に対して責任を持つ。</p>
        </div>
        <p>そんな組織をつくっていきたいと考えています。</p>

        <h3 class="blog-post__subsection-title">信じて任せることも、経営者の仕事</h3>
        <p>今回の勤務体系の変更は、単なる働き方改革ではありませんでした。</p>
        <p>私自身が、メンバーに対する考え方を見直す機会でもありました。</p>
        <p>遅刻を繰り返すスタッフに対して、何度も注意をする。</p>
        <p>それだけでは解決しなかった問題が、理由を聞き、仕組みを変えることで改善しました。</p>
        <p>もし、あのまま指導だけを続けていたら、どうなっていたでしょうか。</p>
        <p>スタッフは通勤の負担を抱えたまま、会社は同じ問題に悩み続けていたかもしれません。</p>
        <p>そう考えると、今回の経験は、私にとって大切な学びになりました。</p>
        <div class="blog-post__intro">
          <p>人を信じることは、何も管理しないことではありません。</p>
        </div>
        <p>お互いの責任を明確にしたうえで、本人が考え、行動できる余地をつくることだと思います。</p>
        <p>これからも、メンバーにはもっと多くの仕事を経験し、新しいスキルを身につけてほしい。</p>
        <p>そして、自分の仕事に誇りを持ってほしい。</p>
        <p>会社の成長は、メンバー一人ひとりの成長の積み重ねです。</p>
        <p>彼らが働きやすい環境をつくり、自主性を尊重することで、結果として会社も成長していく。</p>
        <p>そんな関係を、これからも大切にしたいと思います。</p>
        <div class="blog-post__intro">
          <p>時間を守らせることよりも、約束した仕事を守れる組織をつくること。</p>
        </div>
        <p>今週は、そんな当たり前のようで難しいことを、改めて考えた一週間でした。</p>

