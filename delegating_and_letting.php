        <p>最近、私自身の仕事でも似た変化が起きています。</p>
        <p>AIを使い始めた頃は、文章の作成や調べ物が中心でした。</p>
        <p>しかし今は、事業のアイデアを相談し、業務の進め方を整理し、プログラムの修正まで一緒に進めるようになりました。</p>
