      <section class="blog-post__content">
        <h2 class="blog-post__section-title">「できることをやる」に変えたら、組織が回り始めた</h2>
        <p>日本式を押し付けることをやめて分かった、ミャンマーチームとの向き合い方。</p>

        <p>ミャンマーへ進出した当初、私はかなり勘違いをしていたと思います。</p>
        <p>日本で仕事をしてきた自分のなかには、</p>
        <div class="blog-post__intro">
          <p>「会社とはこうあるべき」<br />「社員管理とはこうするもの」<br />「評価とはこうするもの」</p>
        </div>
        <p>という考えがありました。</p>
        <p>そして、それをそのままミャンマーでも実行しようとしていました。</p>
        <p>業務管理、人材管理、給与、評価。</p>
        <p>日本で経験してきたやり方を「正しいもの」と考え、ミャンマーチームとぶつかってもらおうとしていたのです。</p>
        <p>当時の私は、</p>
        <div class="blog-post__intro">
          <p>「家族の事情を仕事へ持ち込むな」<br />「私情で判断するな」<br />「言い訳をするな」</p>
        </div>
        <p>そんなことをスタッフへ言っていました。</p>
        <p>今振り返ると、ずいぶん厳しいことを言っていたと思います。</p>
        <p>もちろん、仕事である以上、納期や品質も守らなければなりません。</p>
        <p>その考えは今も変わりません。</p>
        <p>ただ、問題だったのは、日本で自分が経験してきた働き方だけを基準にしていたことでした。</p>

        <h3 class="blog-post__subsection-title">結果は、うまくいかなかった</h3>
        <p>離職者も多く、採用しては教育し、また辞める。</p>
        <p>その繰り返しでした。</p>
        <p>スタッフが定着しなければ、経験も知識も蓄積されません。</p>
        <p>当然、品質も安定しません。</p>
        <p>品質が安定しなければ、お客様から継続して仕事をいただくことも難しくなります。</p>
        <p>今思えば、</p>
        <div class="blog-post__flow">
          <p>教育が追いつかない</p>
          <p class="blog-post__flow-arrow">↓</p>
          <p>品質が安定しない</p>
          <p class="blog-post__flow-arrow">↓</p>
          <p>受注が継続しない</p>
        </div>
        <p>という負のスパイラルに入っていました。</p>

        <h3 class="blog-post__subsection-title">あるスタッフとの会話が転機になった</h3>
        <p>そんなとき、あるスタッフとの面談で、私はいつものように、</p>
        <div class="blog-post__intro">
          <p>「なぜその対応になったのか」<br />「もっと仕事として割り切れないのか」</p>
        </div>
        <p>と尋ねていました。</p>
        <p>すると、そのスタッフが少し間を置いて、</p>
        <div class="blog-post__intro">
          <p>「日本でもそうかもしれません。でも、ミャンマーでは家族の事情と仕事を完全に分けることは難しい人も多いです」</p>
        </div>
        <p>と話してくれました。</p>
        <p>さらに、</p>
        <div class="blog-post__intro">
          <p>「会社に迷惑をかけたいわけではありません。みんな仕事は大切にしています。ただ、日本と同じ考え方を求められると、苦しくなる人もいます」</p>
        </div>
        <p>とも言われました。</p>
        <p>そのとき、私は初めて、</p>
        <div class="blog-post__intro">
          <p>「自分は仕事のやり方を教えているつもりで、実は生き方まで合わせてもらおうとしていたのではないか」</p>
        </div>
        <p>と気付きました。</p>
        <p>そこから、考え方を変えました。</p>

        <h3 class="blog-post__subsection-title">自分の役割を変えてみた</h3>
        <p>私は、すべてをスタッフを自分で直接管理することをやめました。</p>
        <p>代わりに、自分が本当にできることへ集中することにしました。</p>
        <p>日本のお客様と話す。<br />案件をつくる。<br />お客様が求めることを理解する。<br />品質基準や業務仕様を現地チームへ伝える。</p>
        <p>一方で、</p>
        <p>スタッフの生活環境。<br />人間関係。<br />現地のコミュニケーション。</p>
        <p>こうしたことは、ミャンマー人のリーダーの方が圧倒的によく分かっています。</p>
        <p>そこで、選んでくれたメンバーを中心に、スタッフ管理を任せました。</p>
        <p>私は「何を実現したいのか」を伝える。</p>
        <p>現地リーダーは、それをミャンマーの文化や考え方に合わせてスタッフへ伝える。</p>
        <p>そういう役割分担に変えました。</p>

        <h3 class="blog-post__subsection-title">不思議なくらい、組織が変わった</h3>
        <p>すると、チームの雰囲気が大きく変わりました。</p>
        <p>メンバーの士気が上がった。<br />会社に活気が出た。<br />スタッフ同士で助け合うようになった。</p>
        <p>そして何より、効率と品質が上がりました。</p>
        <p>以前は、私が細かく管理しているにもかかわらず、品質が安定しませんでした。</p>
        <p>ところが、現地メンバーに任せるようになってから、逆に仕事が安定していったのです。</p>
        <p>この経験から、強く感じたことがあります。</p>
        <div class="blog-post__intro">
          <p>「日本品質」と「日本式管理」は同じではない。</p>
        </div>
        <p>お客様が求めているのは、日本人と働きたいわけではありません。</p>
        <p>求めているのは、</p>
        <p>納期。<br />品質。<br />コミュニケーション。<br />そして、安心して任せられる結果です。</p>
        <p>そこへ到達する方法は、日本とミャンマーで違っていてもいいのだと思います。</p>

        <h3 class="blog-post__subsection-title">現地リーダーは「文化をつなぐ存在」</h3>
        <p>今では、現地リーダーの存在が非常に重要だと感じています。</p>
        <p>日本の側の理解を理解する。</p>
        <p>お客様が求める品質を理解する。</p>
        <p>それで現地メンバーが理解できる形へ変換する。</p>
        <p>逆に、現地メンバーが考えていることを日本語側へ伝える。</p>
        <p>単なる通訳ではなく、考え方と文化をつなぐ存在です。</p>
        <p>こうした役割を任せられるようになってから、スタッフの定着も進みました。</p>
        <p>定着すれば、会社の中に知識が蓄積されます。</p>
        <p>辞める人が新たに入ってくる。<br />新しい人が育つ。<br />その人がまた次の人を育てる。</p>
        <p>その積み重ねで、品質も効率も上がっていきました。</p>

        <h3 class="blog-post__subsection-title">「安いから海外」では続かない</h3>
        <p>以前は、海外拠点というと、どうしても「人件費が安い」という考えが強くありました。</p>
        <p>しかし、</p>
        <p>安い人材を採用し、<br />採用したままにする。<br />教育が十分にできない。<br />品質が安定しない。</p>
        <p>これでは長期的には決して安くありません。</p>
        <p>採用、教育、管理、やり直し、多くのコストがかかります。</p>
        <p>それよりも、人材が定着し、経験が積み上がり、品質が向上していく組織をつくることが、結果的に強い会社につながります。</p>

        <h3 class="blog-post__subsection-title">目指すのは「お客様基準」</h3>
        <p>今は、</p>
        <p>日本基準でも、ミャンマー基準でもなく、お客様が求める品質基準を目指しています。</p>
        <p>その品質へ到達する方法を、日本とミャンマーで一緒に考える。</p>
        <p>それが、今の私たちの仕事の進め方です。</p>
        <p>最近では、AIについても同じことを続けています。</p>
        <p>AIが得意なことはAIに任せる。<br />人が得意なことは人が担当する。</p>
        <p>日本側が得意なこと。<br />ミャンマー側が得意なこと。</p>
        <p>それぞれが、できることをやる。</p>
        <p>それを組み合わせる。</p>
        <p>良い組織づくりも、AI活用も、考え方は似ているのかもしれません。</p>

        <h3 class="blog-post__subsection-title">今では、自分がいなくても組織が回る</h3>
        <p>今では、私が長期現場を離れても、</p>
        <p>設備管理。<br />経費処理。<br />お客様対応。<br />人材採用。</p>
        <p>必要なことを、現地メンバーが進められるようになりました。</p>
        <p>振り返ってみると、その原点は、</p>
        <div class="blog-post__intro">
          <p>「自分が全部管理することをやめたこと」</p>
        </div>
        <p>だったのだと思います。</p>

        <h3 class="blog-post__subsection-title">まとめ</h3>
        <p>ミャンマーへ進出した当初、私は相手を変えようとしていました。</p>
        <p>日本式に考えてもらう。<br />日本式に働いてもらう。<br />日本式に判断してもらう。</p>
        <p>でも、うまくいきませんでした。</p>
        <p>そこで変えたのは、相手ではなく、自分の役割でした。</p>
        <p>自分にできることをやる。<br />相手にできることを任せる。<br />そして、お互いの違いを尊重する。</p>
        <p>そうすると、人は自分で考え始めます。</p>
        <p>組織も、少しずつ自分で動き始めます。</p>
        <div class="blog-post__intro">
          <p>「できることをやる」</p>
        </div>
        <p>今では、それが私たちのチームづくりの原点の一つになっています。</p>
