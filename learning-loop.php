      <section class="blog-post__content">
        <h2 class="blog-post__section-title">3か月ぶりのミャンマーで、あらためて感じたこと</h2>
        <p>「任せる」ということは、信じることなのかもしれない。</p>

        <p>6月から、丸3か月。</p>
        <p>私はミャンマーに来ることができませんでした。</p>
        <p>これほど長くミャンマーを離れたのは、弊社が現地で事業を始めて以来、初めてのことです。</p>
        <p>もちろん、オンラインでは毎日のようにオフィスの様子を見ていました。<br />メンバーとも話していました。<br />仕事の進捗も確認していました。</p>
        <p>画面越しに見る限り、特に大きな変化はありませんでした。</p>
        <p>それでも、正直に言えば、不安はありました。</p>
        <p>自分がいない間に、何か起きていないだろうか。<br />チームの雰囲気は変わっていないだろうか。<br />業務は本当に問題なく回っているだろうか。</p>
        <p>そんなことを、どこかで気にしていたと思います。</p>

        <h3 class="blog-post__subsection-title">戻ってきて、最初に感じたこと</h3>
        <p>今回、3か月ぶりにミャンマーへ戻ってきました。</p>
        <p>オフィスへ行き、メンバーの顔を見て、少し安心しました。</p>
        <p>でも、それ以上に感じたのは、</p>
        <div class="blog-post__intro">
          <p>「自分が思っていた以上に、チームが成長していた」</p>
        </div>
        <p>ということでした。</p>

        <p>私がいない間、<br />メンバーはPC設備のメンテナンスを行い、<br />社内の運転資金を管理し、<br />必要な経費を適切に処理し、<br />日々の業務を止めることなく続けていました。</p>
        <p>さらに、お客様との直接のやり取りも増えていました。</p>
        <p>そして、離職者も出ていませんでした。<br />むしろ、必要な人材が増えている状況です。</p>

        <h3 class="blog-post__subsection-title">「いないから止まる会社」ではなかった</h3>
        <p>正直、驚きました。</p>
        <p>経営をしていると、<br />自分が動いているから会社が回っている。<br />自分が見ているから品質が保たれている。</p>
        <p>どこかで、そう思ってしまうことがあります。</p>
        <p>特に海外拠点では、</p>
        <div class="blog-post__intro">
          <p>「自分がいないと心配」</p>
        </div>
        <p>という感覚を持ちやすいと思います。</p>
        <p>でも今回、その考えを少し改めることになりました。</p>

        <p>私がいなくても、<br />メンバーは必要なことを考え、<br />判断し、<br />行動していました。</p>
        <p>しかも、<br />ただ「問題なくこなしていた」のではありません。</p>
        <p>お客様とのやり取りも増え、<br />業務の範囲も少しずつ広がっていました。</p>
        <p>つまり、<br />止まっていなかっただけではなく、進んでいた。</p>
        <p>そこに、私はとても大きな成長を感じました。</p>

        <h3 class="blog-post__subsection-title">自立とは、何でも一人でやることではない</h3>
        <p>「自立したチーム」という言葉があります。</p>
        <p>私は以前、<br />自立とは、<br />誰の助けも借りずに何でもできること。</p>
        <p>そんなイメージを持っていました。</p>
        <p>でも、今は少し違うように感じています。</p>
        <p>本当の自立とは、</p>
        <p>必要なときに相談する。<br />必要なことを共有する。<br />自分たちで考えられることは、自分たちで考える。<br />判断が必要なことは、確認する。</p>
        <p>そして、<br />自分たちの役割を理解して、責任を持って動く。</p>
        <p>そういうことなのかもしれません。</p>
        <p>今回の3か月で、ミャンマーチームはそれを見せてくれたように思います。</p>

        <h3 class="blog-post__subsection-title">任せるとは、放っておくことではない</h3>
        <p>今回、あらためて感じたことがあります。</p>
        <p>それは、</p>
        <div class="blog-post__intro">
          <p>「任せること」と「放っておくこと」は違う</p>
        </div>
        <p>ということです。</p>
        <p>任せるためには、<br />それまでに、</p>
        <p>ルールをつくる。<br />考え方を共有する。<br />判断基準を伝える。<br />失敗したときに一緒に振り返る。</p>
        <p>そうした積み重ねが必要です。</p>
        <p>そして、その上で、</p>
        <div class="blog-post__intro">
          <p>「やってみて」</p>
        </div>
        <p>と渡す。</p>
        <p>そうして初めて、チームは少しずつ自分たちで動けるようになるのだと思います。</p>

        <h3 class="blog-post__subsection-title">3か月という距離が、見せてくれたもの</h3>
        <p>普段、毎日近くにいると、変化は見えにくいのです。</p>
        <p>少しずつ成長していることに気がつかない。<br />できることが増えているのに、それを当たり前に感じてしまう。</p>
        <p>でも今回、3か月という時間が空いたことで、<br />逆に、その成長を強く感じることができました。</p>

        <p>PC設備の管理。<br />資金や経費の処理。<br />お客様とのやり取り。<br />人材の維持。<br />新しい人材の必要性。</p>
        <p>どれも、小さなことではありません。<br />それを、日々積み重ねていた。</p>
        <p>私はそこに、ミャンマーメンバーの可能性をあらためて感じました。</p>

        <h3 class="blog-post__subsection-title">「育てる」から「一緒に育つ」へ</h3>
        <p>これまで私は、<br />ミャンマーで人材を育てること。<br />チームを育てること。</p>
        <p>そういう意識を強く持ってきたと思います。</p>
        <p>でも今回、<br />少し考え方が変わりました。</p>
        <p>会社が人を育てるだけではない。<br />人も会社を育てる。</p>
        <p>そして、<br />会社と人が一緒に成長する。</p>
        <p>今は、そんな感覚の方が近いように思います。</p>
        <p>メンバーが成長すれば、<br />任せられることが増える。<br />任せられることが増えれば、<br />会社としてできることも増える。<br />会社が成長すれば、<br />また新しい仕事や機会をメンバーに提供できる。</p>
        <p>この循環をつくることが、これからとても大切だと感じています。</p>

        <h3 class="blog-post__subsection-title">AIの時代でも、会社を動かすのは人</h3>
        <p>今、私たちはAIやBPO、KPOについて多く発信しています。</p>
        <p>AIはこれから、さらに多くの仕事を支えてくれるでしょう。</p>
        <p>でも今回、改めて感じたことがあります。</p>
        <p>どれだけAIが進化しても、<br />会社を支えるのは人です。</p>
        <p>判断する人。<br />お客様と話す人。<br />困ったときに動く人。<br />誰かを支える人。<br />会社の未来を考える人。</p>
        <p>そこに人がいるから、会社は前へ進めるのだと思います。</p>

        <h3 class="blog-post__subsection-title">このメンバーと、もっと先へ行きたい</h3>
        <p>今回、3か月ぶりにミャンマーへ戻り、<br />私はとても嬉しく感じました。</p>
        <div class="blog-post__intro">
          <p>「問題がなくて安心した」</p>
        </div>
        <p>というだけではありません。</p>
        <div class="blog-post__intro">
          <p>「このメンバーなら、もっと先へ行けるかもしれない」</p>
        </div>
        <p>そう感じました。</p>
        <p>今まで任せられなかった仕事も、<br />少しずつ任せていける。</p>
        <p>お客様とのやり取りも、<br />もっと広げていける。</p>
        <p>新しいサービスも、<br />一緒につくっていける。</p>
        <p>そんな可能性を感じています。</p>

        <h3 class="blog-post__subsection-title">まとめ</h3>
        <p>3か月、ミャンマーに来ることができませんでした。</p>
        <p>最初は不安でした。</p>
        <p>でも、戻ってきて感じたのは、<br />不安よりも、<br />成長への驚きと、期待<br />でした。</p>
        <p>自分がいなくても、<br />メンバーは考え、<br />動き、<br />会社を支えてくれていました。</p>
        <p>そして会社は止まっていませんでした。<br />むしろ、少しずつ前へ進んでいました。</p>
        <p>今回、あらためて思いました。</p>
        <p>会社は、一人でつくるものではありません。<br />一緒に働く人たちと、<br />考え、<br />任せ、<br />失敗し、<br />学び、<br />成長していくものなのだと思います。</p>
        <p>これからも私は、<br />このメンバーと一緒に、<br />A CAN SOLUTIONSをもっと良い会社へ育てていきたいと思っています。</p>
        <p>3か月ぶりのミャンマーで、<br />そんなことをあらためて感じた一週間でした。</p>
