      <section class="blog-post__content">
        <h2 class="blog-post__section-title">「納期に間に合わせたい」と、自分たちで動くチーム</h2>

        <p>ミャンマーのメンバーを見て、改めて思ったこと。</p>

        <p>仕事をしていると、時々、予定していた受注数を大幅に上回ることがあります。</p>
        <p>もちろん、そんな時はお客様に対して説明し、納期について相談させていただくことがあります。</p>
        <p>無理なものは無理です。</p>
        <p>品質を落としてまで、納期だけを守ることが正しいとも思っていません。</p>

        <p>ところが、そんな時のミャンマーメンバーを見ていると、時々驚かされます。</p>
        <div class="blog-post__intro">
          <p>「納期を延ばしてもらえるから大丈夫」</p>
        </div>
        <p>ではないのです。</p>
        <div class="blog-post__intro">
          <p>「できるだけ当初の納期に間に合わせるには、どうすればいいか」</p>
        </div>
        <p>を、自分たちで考え始めます。</p>

        <h3 class="blog-post__subsection-title">誰かに言われる前に、動き始める</h3>
        <p>業務量を確認する。<br />メンバーの稼働状況を確認する。<br />担当を組み替える。<br />必要であれば、自分たち稼働時間を調整する。</p>
        <p>もちろん、会社として無理な働き方を求めているわけではありません。</p>
        <p>それでも、</p>
        <div class="blog-post__intro">
          <p>「お客様がこの日までに必要としている」</p>
        </div>
        <p>ということを理解し、その期限に少しでも応えようと、自分たちで考えて動いてくれます。</p>
        <p>私は、この「自分たちで」というところに大きな価値を感じています。</p>
        <p>指示されたから頑張る。<br />上司に言われたから頑張る。</p>
        <p>そうではありません。</p>
        <p>お客様の事情を考えて、自分たちができることを考える。</p>
        <p>これは、単なる作業者ではなく、仕事を任された側としての責任感だと思います。</p>

        <h3 class="blog-post__subsection-title">海外で仕事をしてきたからこそ、驚くこともあります</h3>
        <p>私はこれまで、ミャンマー以外のアジアの国々でも仕事をしてきました。</p>
        <p>その中では、納期が厳しくなった時に、</p>
        <div class="blog-post__intro">
          <p>「残業するのであれば、まず追加費用を決めましょう」</p>
        </div>
        <p>という現場もありました。</p>
        <div class="blog-post__intro">
          <p>「納期についてはベストエフォートです」</p>
        </div>
        <p>という考え方もありました。</p>
        <p>あるいは、まず労働時間やルールについて確認するところから始まることもありました。</p>
        <p>もちろん、どれが正しい、間違っているという話ではありません。</p>
        <p>労働時間を守ることも、労働者に対して正当な対価を求めることも当然です。</p>
        <p>ただ、そうした経験をしてきた私からすると、今のミャンマーチームの姿勢には、驚かされることがあります。</p>
        <p>「まず、お客様の期待にどう応えるかを考える」という姿勢が、現場に根付いているからです。</p>
        <p>しかも、それを日本から細かく指示しているわけではありません。</p>
        <p>ミャンマーの現場で、マネージャー、業務リーダー、そしてメンバー自身が考えて動いています。</p>

        <h3 class="blog-post__subsection-title">実力だけを比較すれば、日本人に及ばない部分もある</h3>
        <p>もちろん、すべてが完璧というわけではありません。</p>
        <p>業務経験。<br />専門知識。<br />日本語。<br />判断の違い。<br />仕事の細かなニュアンス。</p>
        <p>実力面だけを比較すれば、まだ日本人スタッフに及ばない部分もあります。</p>
        <p>だから教育も必要です。</p>
        <p>確認も必要です。</p>
        <p>失敗することもあります。</p>
        <p>でも、私は最近思います。</p>
        <p>お客様からいただいた仕事に対する考え方は、決して負けていない。</p>
        <p>分からなければ聞く。<br />間違えれば直す。<br />仕事を頼まれれば、どうすれば対応できるか考える。</p>
        <p>そして、お客様が求めている納期に少しでも近づけようとする。</p>
        <p>スキルは、経験と教育によって伸ばすことができます。</p>
        <p>でも、</p>
        <div class="blog-post__intro">
          <p>「この仕事をきちんと届けたい」</p>
        </div>
        <p>という気持ちは、マニュアルだけで簡単につくれるものではありません。</p>

        <h3 class="blog-post__subsection-title">BPOで本当に大切なのは、これかもしれない</h3>
        <p>BPOというと、</p>
        <div class="blog-post__intro">
          <p>「人件費はいくらか」<br />「1件いくらで処理できるか」<br />「日本と比べて何％安いか」</p>
        </div>
        <p>といった数字で比較されることが多いと思います。</p>
        <p>もちろん、コストは重要です。</p>
        <p>でも、実際に仕事を任せる立場になれば、それだけでは足りません。</p>
        <p>予定外のことが起きた時に、どうするか。</p>
        <p>マニュアルに書いていない状況で、どう判断するか。</p>
        <p>そして、お客様の立場に立って、もう一歩考えられるか。</p>
        <p>私は、そこにBPOチームの本当の価値が出ると思っています。</p>

        <div class="blog-post__intro">
          <p>「そんなチームが、ミャンマーにある」</p>
        </div>
        <p>政治情勢が不安定。<br />停電もある。<br />通信環境にも問題がある。</p>
        <p>決して簡単な環境ではありません。</p>
        <p>それでも、</p>
        <p>お客様から仕事をいただき、<br />納期を考え、<br />品質を考え、<br />自分たちで相談し、</p>
        <div class="blog-post__intro">
          <p>「どうすれば間に合わせられるだろう」</p>
        </div>
        <p>と働いているメンバーがいる。</p>
        <p>しかも、それがミャンマーにある。</p>

        <p>10年前、この国で仕事を始めた時には、今のようなチームになるとは想像できていませんでした。</p>
        <p>会社をつくるのは経営者かもしれません。</p>
        <p>でも、チームをつくるのは、そこで働く人たちです。</p>
        <p>今のチームをここまで育ててくれたマネージャー。<br />現場を支えてくれている業務リーダー。<br />そして、毎日お客様の仕事に向き合ってくれているメンバー。</p>
        <p>改めて、感謝したいと思います。</p>

        <p>まだまだ成長途中のチームです。</p>
        <p>もっとできることもある。<br />もっと品質を上げることもできる。</p>
        <p>でも私は、</p>
        <div class="blog-post__intro">
          <p>「この人たちとなら、もっと良い仕事ができる」</p>
        </div>
        <p>そう思っています。</p>

        <p>日曜日。<br />少しだけ、ミャンマーの仲間を自慢したくなりました。</p>
