        <h2 class="blog-post__section-title">支えるということ</h2>
        <p>厳しいミャンマーで、あらためて考えた「一緒に働く」という意味。</p>

        <p>今、ミャンマーの生活は決して楽ではありません。</p>
        <p>9月だけを見ても、チャット安が進み、燃料価格も上昇しました。</p>
        <p>私たちが日常生活の中で見ている価格でも、<br />食事、交通費、卵、外食など、<br />さまざまなものが以前より高くなっています。</p>
        <p>数字だけを見れば、</p>
        <div class="blog-post__intro">
          <p>「物価が上がっている」</p>
        </div>
        <p>という一言で表現できます。</p>
        <p>しかし、現地で生活していると、その数字の向こう側にあるものが見えてきます。</p>

        <h3 class="blog-post__subsection-title">物価上昇は、生活そのものに影響する</h3>
        <p>ミャンマーでは、外貨を持っている人と、MMKだけで生活している人とでは、現在の環境から受ける影響が大きく違います。</p>
        <p>日本円や米ドルを受け取れる人にとっては、チャット安によって多少は物価上昇を吸収できます。</p>
        <p>しかし、収入のほとんどがMMKの人にとっては、</p>
        <p>物価が上がっても、<br />給与が同じ速度で上がるわけではありません。</p>
        <p>食費が上がる。<br />交通費が上がる。<br />燃料が上がる。<br />生活に必要な支出が少しずつ増えていく。</p>
        <p>その積み重ねが、暮らしを圧迫しています。</p>

        <h3 class="blog-post__subsection-title">身近なところでも感じる厳しさ</h3>
        <p>私が普段お願いしているタクシーの運転手がいます。</p>
        <p>その彼が最近、事故に巻き込まれました。</p>
        <p>自分の車を当て逃げされ、修理ができないまま、すでに2か月ほど仕事ができていません。</p>
        <p>車がなければ仕事ができない。</p>
        <p>しかし、<br />修理するための部品がない。<br />そして、その部品を買うためのお金もない。</p>
        <p>日本であれば、<br />保険や修理、代車など、<br />何らかの方法が見つかるケースも多いと思います。</p>
        <p>しかし、ここでは、<br />一つの事故が、<br />そのまま「仕事を失うこと」につながることがあります。</p>
        <p>本人が怠けているわけでもない。<br />働きたくないわけでもない。<br />仕事をしたくても、<br />できない。</p>
        <p>そういう状況を、身近なところで見ることがあります。</p>

        <h3 class="blog-post__subsection-title">「寄付をすればいい」のか</h3>
        <p>こうした話をすると、</p>
        <div class="blog-post__intro">
          <p>「何か支援できないか」</p>
        </div>
        <p>と考えます。</p>
        <p>もちろん、<br />困っている人に対して、お金を渡すことが必要な場面もあると思います。</p>
        <p>しかし、私は今、<br />少し違うことを考えました。</p>
        <p>単純に寄付をすることだけが、<br />本当にその人のためになるのだろうか。</p>
        <p>一時的にお金を渡せば、<br />その瞬間は助かります。</p>
        <p>でも、<br />生活を安定させ、<br />その人自身が将来へ進んでいくためには、<br />それだけでは足りないように感じます。</p>

        <h3 class="blog-post__subsection-title">「仕事」で支えるという考え方</h3>
        <p>私たちは会社です。</p>
        <p>だからこそ、<br />できる支援の形もあると思っています。</p>
        <p>それは、<br />仕事をつくること。</p>
        <p>そして、<br />その仕事を正当に評価すること。</p>
        <p>働いた分に対して、<br />適切な報酬を支払う。</p>
        <p>能力が上がれば、<br />その成長を評価する。<br />新しい仕事を任せる。<br />スキルを学べる環境をつくる。<br />将来のキャリアを一緒に考える。</p>
        <p>そうすることで、</p>
        <div class="blog-post__intro">
          <p>「支援する側」と「支援される側」ではなく、<br />一緒に働く仲間</p>
        </div>
        <p>という関係をつくることができるのではないかと思います。</p>

        <h3 class="blog-post__subsection-title">安いからミャンマーを使う、では続かない</h3>
        <p>チャット安が進むと、<br />日本企業から見れば、<br />ミャンマーの人件費は相対的に安く見えることがあります。</p>
        <p>しかし、<br />そこで、</p>
        <div class="blog-post__intro">
          <p>「さらに安く使える」</p>
        </div>
        <p>とだけ考えてしまえば、<br />長期的な関係は続かないと思います。</p>
        <p>スタッフ自身はMMKで生活しています。</p>
        <p>食費も、<br />交通費も、<br />家賃も、<br />通信費も、<br />生活に必要なものは上がっています。</p>
        <p>だから、<br />為替だけを見て給与を考えるのではなく、<br />現地で実際にどのような生活をしているのか<br />を見る必要があります。</p>

        <h3 class="blog-post__subsection-title">正当に評価することも支援になる</h3>
        <p>私は最近、<br />「支援」という言葉について考えるようになりました。</p>
        <p>支援というと、<br />何かを無償で与えることを想像しがちです。</p>
        <p>しかし、<br />仕事を正しく評価することも、十分に支援なのではないか<br />と思います。</p>
        <p>頑張った人には、<br />頑張っただけの評価をする。<br />責任が増えれば、<br />それに応じた報酬を考える。<br />物価が大きく変われば、<br />生活への影響も考える。</p>
        <p>そして、<br />目の前の給与だけではなく、<br />その先の成長まで一緒に考える。</p>
        <p>会社だからこそできる支援は、<br />そこにあるのかもしれません。</p>

        <h3 class="blog-post__subsection-title">お金だけではない支援</h3>
        <p>一方で、<br />すべてがお金で解決するわけではありません。</p>
        <p>例えば、</p>
        <p>新しい仕事を経験する機会。<br />AIやITを学ぶ機会。<br />日本語を学ぶ機会。<br />チームを管理する経験。<br />お客様と直接話す経験。</p>
        <p>こうしたものも、<br />長い目で見れば大きな価値になります。</p>
        <p>今の収入だけではなく、<br />3年後、5年後に何ができる人材になっているか。</p>
        <p>そこまで考えることが、<br />会社としての役割だと思っています。</p>

        <h3 class="blog-post__subsection-title">一人ひとりの生活を見る</h3>
        <p>会社が大きくなると、<br />どうしても数字を見る機会が増えます。</p>
        <p>売上。<br />利益。<br />人件費。<br />生産性。<br />稼働率。</p>
        <p>もちろん、経営には必要です。</p>
        <p>でも、<br />その数字の向こう側には、<br />一人ひとりの生活があります。</p>
        <p>家族がいる人。<br />親を支えている人。<br />兄弟の学費を負担している人。<br />将来のために勉強している人。<br />生活が苦しくても、毎日会社へ来て仕事をしている人。</p>
        <p>そこを忘れてはいけないと、改めて感じています。</p>

        <h3 class="blog-post__subsection-title">会社とメンバーは、同じ方向を向けるか</h3>
        <p>私が目指したいのは、<br />会社が利益を出して、<br />メンバーはただ給与を受け取る。<br />というだけの関係ではありません。</p>
        <p>会社が成長する。<br />メンバーも成長する。<br />会社の仕事が増える。<br />メンバーの機会も増える。<br />メンバーの能力が上がる。<br />会社が提供できるサービスも増える。</p>
        <p>そういう循環をつくりたいと思っています。</p>

        <h3 class="blog-post__subsection-title">AI時代だからこそ、人への投資を減らさない</h3>
        <p>今後、<br />AIによって多くの業務が効率化されていくと思います。</p>
        <p>だからといって、<br />人への投資を減らすべきだとは思いません。</p>
        <p>むしろ逆です。</p>
        <p>単純作業がAIへ移るのであれば、<br />人には、</p>
        <p>より高度な仕事を任せられるようにする。<br />AIを使えるようにする。<br />品質を管理できるようにする。<br />お客様と話せるようにする。<br />改善を提案できるようにする。</p>
        <p>そのための教育が必要になります。</p>

        <h3 class="blog-post__subsection-title">一緒に働くことが、喜びになる会社へ</h3>
        <p>私は、</p>
        <div class="blog-post__intro">
          <p>「生活のために仕方なく働く」</p>
        </div>
        <p>だけの会社にはしたくありません。</p>
        <p>もちろん、<br />仕事は生活のためでもあります。<br />給与はとても大切です。</p>
        <p>でも、<br />それだけではなく、</p>
        <p>「ここで働いて成長できた」<br />「新しい仕事を覚えた」<br />「自分の仕事がお客様の役に立った」<br />「このチームで働けてよかった」</p>
        <p>と思ってもらえる会社にしたい。</p>
        <p>そして、<br />私自身も、<br />このメンバーと一緒に会社を成長させることを楽しみたいと思っています。</p>

        <h3 class="blog-post__subsection-title">まとめ</h3>
        <p>今のミャンマーは、<br />決して簡単な状況ではありません。</p>
        <p>チャット安。<br />物価上昇。<br />燃料コストの増加。</p>
        <p>それぞれが、市民生活に直接影響しています。</p>
        <p>そんな環境にいるからこそ、<br />会社として何ができるのか。</p>
        <p>改めて考えています。</p>
        <p>単純にお金を渡すことだけではなく、</p>
        <p>仕事をつくる。<br />仕事を正当に評価する。<br />生活の状況を見る。<br />成長する機会をつくる。<br />将来のキャリアを一緒に考える。</p>
        <p>そして、<br />必要なときには支える。</p>
        <p>私は、<br />そういう関係をメンバーとつくっていきたいと思っています。</p>
        <p>仕事を通して生活を支え、<br />成長を通じて未来を支える。</p>
        <p>そして、<br />その結果として、<br />「一緒に働くことが喜びになる」。</p>
        <p>そんな会社を、<br />このミャンマーのメンバーと一緒につくっていきたい。</p>
        <p>今週は、そんなことを強く感じた一週間でした。</p>
