        <p>AIの普及により、BPO・KPOの役割が大きく変わっています。</p>
        <p>従来は「人が業務を代行すること」が中心でしたが、これからは、</p>
        <ul class="blog-post__list">
          <li>AIを管理する</li>
          <li>人が品質を保証する</li>
          <li>継続的に改善を行う</li>
        </ul>
        <p>という新しい形態が求められます。</p>
        <p>つまり、人がAI運用体制を設計・実行する企業が、これからのBPO・KPOの価値を生み出していくのです。</p>
      </section>

