      <section class="blog-post__content" id="section-1">
        <h2 class="blog-post__section-title">1. なぜBPOの「丸投げ」は失敗するのか</h2>

        <p>長年社内で行われてきた業務には、想像以上に多くの「暗黙知」が存在します。</p>
        <p>例えば、</p>
        <div class="blog-post__intro">
          <p>「この場合はAで処理する」<br />「ただし、このお客様だけはBにする」<br />「金額が一定以上なら担当者へ確認する」</p>
        </div>
        <p>といったルールです。</p>
        <p>社内では当たり前になっているため、マニュアルに書かれていないことも珍しくありません。</p>
        <p>その状態で、</p>
        <p>「このマニュアルを見て、来週からお願いします」</p>
        <p>と業務を移管すると、現場では判断できないケースが次々と発生します。</p>
        <p>これは海外BPOだから起こる問題ではありません。</p>
        <p>業務そのものが十分に整理されていないことが原因です。</p>
        <p>だからこそ、BPO導入の最初に必要なのは、</p>
        <p>「仕事を渡すこと」ではなく「仕事を見える化すること」</p>
        <p>なのです。</p>
      </section>

      <!-- Section 2 -->
      <section class="blog-post__content" id="section-2">
        <h2 class="blog-post__section-title">2. 1〜5日目</h2>
        <h3 class="blog-post__subsection-title">まずは業務を「分解」する</h3>

        <p>最初に行うのは、現在の業務を整理することです。</p>
        <p>例えば請求書処理であれば、</p>
        <ol class="blog-post__list">
          <li>請求書を受領する</li>
          <li>会社名を確認する</li>
          <li>金額を確認する</li>
          <li>内容を入力する</li>
          <li>入力結果をチェックする</li>
          <li>会計システムへ登録する</li>
          <li>担当者が承認する</li>
        </ol>
        <p>というように、業務を工程単位に分解します。</p>
        <p>すると、</p>
        <div class="blog-post__intro">
          <p>「ここまではBPO化できる」<br />「ここはAIで処理できる」<br />「ここだけは社内判断が必要」</p>
        </div>
        <p>といった役割分担が見えてきます。</p>
        <p>BPO導入は、単なる外注ではありません。</p>
        <p>業務そのものを見直す機会でもあります。</p>
      </section>

      <!-- Section 3 -->
      <section class="blog-post__content" id="section-3">
        <h2 class="blog-post__section-title">3. 6〜10日目</h2>
        <h3 class="blog-post__subsection-title">マニュアルより先に「判断基準」をつくる</h3>

        <p>業務を整理したら、次は作業ルールを明確にします。</p>
        <p>ここで重要なのは、操作方法だけを書いたマニュアルを作らないことです。</p>
        <p>例えば、</p>
        <div class="blog-post__intro">
          <p>「このボタンを押す」</p>
        </div>
        <p>だけではなく、</p>
        <p>「どのような場合に、このボタンを押すのか」</p>
        <p>まで整理します。</p>
        <p>特に重要なのが、</p>
        <ul class="blog-post__list">
          <li>OK例</li>
          <li>NG例</li>
          <li>判断に迷う例</li>
          <li>エスカレーション条件</li>
          <li>例外処理</li>
        </ul>
        <p>です。</p>
        <p>BPOの品質は、作業スピードよりも判断基準をどれだけ共有できるかによって大きく変わります。</p>
      </section>

      <!-- Section 4 -->
      <section class="blog-post__content" id="section-4">
        <h2 class="blog-post__section-title">4. 11〜15日目</h2>
        <h3 class="blog-post__subsection-title">少量のトライアルから始める</h3>

        <p>ルールが整理できたら、実際のデータを使ってトライアルを開始します。</p>
        <p>ここで、いきなり大量の業務を移管する必要はありません。</p>
        <p>例えば通常、1日500件ある業務でも、</p>
        <div class="blog-post__intro">
          <p>最初は10件。<br />次に30件。<br />その次に50件。</p>
        </div>
        <p>というように、少量から始めます。</p>
        <p>重要なのは処理件数ではありません。</p>
        <p>どこで判断に迷うのかを見つけることです。</p>
        <p>実際に作業を始めると、</p>
        <p>「マニュアルにこのケースがない」<br />「この判断基準では分からない」<br />「この入力方法の方が効率的ではないか」</p>
        <p>といった問題が必ず出てきます。</p>
        <p>これは失敗ではありません。</p>
        <p>むしろトライアルの目的は問題を早く見つけることなのです。</p>
      </section>

      <!-- Section 5 -->
      <section class="blog-post__content" id="section-5">
        <h2 class="blog-post__section-title">5. 16〜20日目</h2>
        <h3 class="blog-post__subsection-title">最初は「全数チェック」する</h3>

        <p>トライアル初期では、処理した結果を可能な限り細かく確認します。</p>
        <p>私たちは、この段階では全数チェックを基本と考えます。</p>
        <p>なぜなら、初期段階では、</p>
        <p>「どのようなミスが起こるか」</p>
        <p>がまだ分からないからです。</p>
        <p>例えば100件処理して3件のエラーがあった場合、</p>
        <p>単に「正解率97%だった」で終わらせません。</p>
        <p>重要なのは、</p>
        <p>なぜ3件間違えたのか</p>
        <p>です。</p>
        <ul class="blog-post__list">
          <li>判断基準が曖昧だったのか。</li>
          <li>マニュアルが不足していたのか。</li>
          <li>教育が必要なのか。</li>
          <li>単純な確認漏れなのか。</li>
        </ul>
        <p>原因によって改善方法は変わります。</p>
      </section>

      <!-- Section 6 -->
      <section class="blog-post__content" id="section-6">
        <h2 class="blog-post__section-title">6. ミスを「人の問題」にしない</h2>

        <p>BPO立ち上げで特に大切にしたいのが、この考え方です。</p>
        <p>ミスが発生すると、</p>
        <div class="blog-post__intro">
          <p>「担当者が間違えた」</p>
        </div>
        <p>という結論になりがちです。</p>
        <p>しかし、それだけでは品質は改善しません。</p>
        <p>私たちは、</p>
        <p>人のミスを、仕組みの改善につなげる</p>
        <p>ことが重要だと考えています。</p>
        <p>例えば同じ間違いが複数回発生したのであれば、</p>
        <ul class="blog-post__list">
          <li>マニュアルを修正する</li>
          <li>チェック項目を追加する</li>
          <li>入力画面を改善する</li>
          <li>AIによる警告を入れる</li>
        </ul>
        <p>といった対策を検討できます。</p>
        <p>一つのミスから仕組みを一つ改善する。</p>
        <p>この積み重ねが、安定したBPOをつくります。</p>
      </section>

      <!-- Section 7 -->
      <section class="blog-post__content" id="section-7">
        <h2 class="blog-post__section-title">7. 21〜25日目</h2>
        <h3 class="blog-post__subsection-title">品質を確認しながら処理量を増やす</h3>

        <p>一定の品質が確認できたら、少しずつ処理量を増やします。</p>
        <p>例えば、</p>
        <div class="blog-post__intro">
          <p>10件 → 30件 → 50件 → 100件</p>
        </div>
        <p>というように段階的に拡大します。</p>
        <p>ここで重要なのは、</p>
        <p>「100件処理できたから次は200件」</p>
        <p>ではありません。</p>
        <p>確認すべきなのは、</p>
        <ul class="blog-post__list">
          <li>処理件数</li>
          <li>エラー率</li>
          <li>処理時間</li>
          <li>判断不能件数</li>
          <li>手戻り件数</li>
        </ul>
        <p>などです。</p>
        <p>量と品質の両方を確認しながら拡大する。</p>
        <p>これが重要です。</p>
      </section>

      <!-- Section 8 -->
      <section class="blog-post__content" id="section-8">
        <h2 class="blog-post__section-title">8. 26〜30日目</h2>
        <h3 class="blog-post__subsection-title">「全数検査」から「品質管理」へ</h3>

        <p>品質が安定してきたら、すべてを確認する運用から次の段階へ移行します。</p>
        <p>例えば、</p>
        <ul class="blog-post__list">
          <li>通常案件は現地チームで完結する。</li>
          <li>一定割合を抜き取り検査する。</li>
          <li>特殊案件だけ日本側へエスカレーションする。</li>
          <li>エラー傾向を定期的に分析する。</li>
        </ul>
        <p>という運用です。</p>
        <p>日本側が永遠に全件チェックしていたら、BPOを導入した意味が薄れてしまいます。</p>
        <p>最終的に目指すのは、</p>
        <p>「日本が品質をチェックする状態」ではなく、「現地で品質をつくれる状態」</p>
        <p>です。</p>
      </section>

      <!-- Section 9 -->
      <section class="blog-post__content" id="section-9">
        <h2 class="blog-post__section-title">9. 30日後に目指す状態</h2>

        <p>BPO開始から30日で、すべてを完璧にする必要はありません。</p>
        <p>しかし、少なくとも、</p>
        <ul class="blog-post__list">
          <li><strong>業務</strong>：何をBPOへ任せるかが明確になっている。</li>
          <li><strong>品質</strong>：OK・NGの基準が共有されている。</li>
          <li><strong>人</strong>：担当者が業務の目的まで理解している。</li>
          <li><strong>仕組み</strong>：チェック・エスカレーション方法が決まっている。</li>
          <li><strong>改善</strong>：問題を共有し、改善するサイクルができている。</li>
        </ul>
        <p>この状態まで持っていくことが重要です。</p>
        <p>ここまでできれば、その後は処理量を増やしながら、さらに効率化を進められます。</p>
      </section>

      <!-- Section 10 -->
      <section class="blog-post__content" id="section-10">
        <h2 class="blog-post__section-title">10. AIを組み合わせるなら「業務を理解してから」</h2>

        <p>最近では、</p>
        <div class="blog-post__intro">
          <p>「最初からAIで自動化したい」</p>
        </div>
        <p>というご相談も増えています。</p>
        <p>もちろんAIは非常に有効です。</p>
        <p>しかし、業務ルールが整理されていない状態でAIを導入しても、うまく機能しないことがあります。</p>
        <p>まず、</p>
        <ul class="blog-post__list">
          <li>業務を整理する。</li>
          <li>判断基準をつくる。</li>
          <li>例外を把握する。</li>
        </ul>
        <p>その上で、</p>
        <p>「ここはAIに任せられる」</p>
        <p>という工程を見つけます。</p>
        <p>例えば、</p>
        <ul class="blog-post__list">
          <li><strong>AI</strong>：OCR、分類、データ抽出、要約、一次判定</li>
          <li><strong>BPOチーム</strong>：確認、修正、例外処理、品質チェック</li>
          <li><strong>日本側</strong>：最終判断、業務設計、改善</li>
        </ul>
        <p>という役割分担です。</p>
        <p>AI導入もBPO導入も、最初に必要なのは同じです。</p>
        <p>業務を理解することです。</p>
      </section>

      <!-- Section 11 -->
      <section class="blog-post__content" id="section-11">
        <h2 class="blog-post__section-title">11. A CAN SOLUTIONSが考えるBPO導入</h2>

        <p>私たちは、お客様から業務をいただいて、すぐに大量処理することだけを目指しているわけではありません。</p>
        <ul class="blog-post__list">
          <li>まず小さく始める。</li>
          <li>実際に作業する。</li>
          <li>問題を見つける。</li>
          <li>改善する。</li>
          <li>品質を確認する。</li>
          <li>そして徐々に業務量を増やす。</li>
        </ul>
        <p>このプロセスを、日本とミャンマーのチームで一緒につくっていきます。</p>
        <p>私たちが目指しているのは、</p>
        <p>「仕事を受け取るBPO」ではなく「仕事を一緒につくるBPO」</p>
        <p>です。</p>
